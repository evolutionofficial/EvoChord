// Build the app shell: concatenate the modular sources (in file-name order, exactly like the
// original single-file EvoLyric) and bundle the chord engines.
//   src/index.html + src/styles/*.css → www/index.html (CSS inlined in one <style>, as EvoLyric:
//                                       the colour-tone feature reads that stylesheet)
//   src/app/*.js     → www/app.js      (one script, so functions and globals behave as before)
//   src/core/index.js → www/js/evocore.js (window.EvoCore)
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { build } from 'esbuild';

const cat = (dir, ext) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(ext))
    .sort()
    .map((f) => `/* ===== ${dir}/${f} ===== */\n` + readFileSync(`${dir}/${f}`, 'utf8'))
    .join('');

const banner = '/* Generated by tools/build.mjs – edit the files in src/, not this file. */\n';
const tpl = readFileSync('src/index.html', 'utf8');
if (!tpl.includes('/*@APP_CSS@*/')) throw new Error('src/index.html lost its /*@APP_CSS@*/ marker');
writeFileSync('www/index.html', tpl.replace('/*@APP_CSS@*/', () => cat('src/styles', '.css').trimEnd()));
writeFileSync('www/app.js', banner + cat('src/app', '.js'));
mkdirSync('www/js', { recursive: true });
await build({ entryPoints: ['src/core/index.js'], bundle: true, format: 'iife', globalName: 'EvoCore', minify: true, charset: 'ascii', outfile: 'www/js/evocore.js', logLevel: 'warning' });
console.log('built www/index.html, www/app.js, www/js/evocore.js');
